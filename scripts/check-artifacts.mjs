#!/usr/bin/env node
// Gate: validates a docs/architecture artifact set against the AI Architect
// contract. Usage: node scripts/check-artifacts.mjs [path/to/docs/architecture]
// Defaults to docs/architecture under the current working directory.
//
// Checks: every contract file exists; every generated markdown file ends
// with the stamp line; WORKFLOW.md has a 5-column stage table; SYSTEM.md has
// a decisions table with evidence pointers; architecture.json validates
// against the ai-architect.architecture.v1 shape.
//
// Prints a gate table. Exits 1 if any row FAILs. Exits 0 with SKIPPED if the
// target directory does not exist at all (nothing to check yet).

import { readFileSync, existsSync, readdirSync } from 'node:fs';
import path from 'node:path';
import { parseWorkflow } from './parse-workflow.mjs';

const STAMP_LINE = 'Generated by AI Architect · https://www.frankx.ai/ai-architect';
const GATE_IDS = [
  'gate.frame', 'gate.discovery', 'gate.flow', 'gate.decisions', 'gate.economics',
  'gate.trust', 'gate.evals', 'gate.operate', 'gate.verify',
];
const DECISION_KEYS = ['model', 'loop', 'trust', 'run'];
const PLANE_KEYS = ['experience', 'observability', 'evaluation', 'orchestration', 'tools', 'context', 'model'];

const FIXED_MARKDOWN_FILES = [
  'SYSTEM.md', 'WORKFLOW.md', 'SOP.md',
  '00-frame.md', '01-discovery.md', '02-user-flows.md', '03-experience-blueprint.md',
  '04-roi.md', '05-trust-boundary.md', '07-runbook.md',
  '06-evals/rubric.md', 'review.md',
];
const FIXED_DATA_FILES = ['prices.json', '06-evals/cases.jsonl', 'architecture.json'];

const dirArg = process.argv[2] || path.join('docs', 'architecture');
const targetDir = path.resolve(process.cwd(), dirArg);

const rows = [];
function check(name, ok, detail) {
  rows.push({ name, status: ok ? 'PASS' : 'FAIL', detail: detail || '' });
  return ok;
}

if (!existsSync(targetDir)) {
  console.log(`SKIPPED artifacts: ${path.relative(process.cwd(), targetDir) || dirArg} not found`);
  process.exit(0);
}

function read(rel) {
  const full = path.join(targetDir, rel);
  return existsSync(full) ? readFileSync(full, 'utf8') : null;
}

function globCount(dir, matcher) {
  const full = path.join(targetDir, dir);
  if (!existsSync(full)) return [];
  return readdirSync(full).filter(matcher).map((f) => path.join(dir, f));
}

// 1. fixed files exist
for (const rel of [...FIXED_MARKDOWN_FILES, ...FIXED_DATA_FILES]) {
  check(`file: ${rel}`, existsSync(path.join(targetDir, rel)), existsSync(path.join(targetDir, rel)) ? 'present' : 'missing');
}

// 1b. glob-required families
const adrFiles = globCount('adr', (f) => /^ADR-\d{4}-.+\.md$/.test(f));
check('adr: at least one ADR-####-<slug>.md', adrFiles.length > 0, `${adrFiles.length} found`);

const receiptFiles = globCount('receipts', (f) => /^\d{4}-\d{2}-\d{2}-verify\.md$/.test(f));
check('receipts: at least one <YYYY-MM-DD>-verify.md', receiptFiles.length > 0, `${receiptFiles.length} found`);

// 2. stamp line on every generated markdown file (fixed + found ADRs/receipts)
const stampTargets = [...FIXED_MARKDOWN_FILES, ...adrFiles, ...receiptFiles];
for (const rel of stampTargets) {
  const content = read(rel);
  if (content === null) {
    check(`stamp: ${rel}`, false, 'file missing, cannot check stamp');
    continue;
  }
  check(`stamp: ${rel}`, content.includes(STAMP_LINE), content.includes(STAMP_LINE) ? 'present' : 'stamp line missing or altered');
}

// 3. WORKFLOW.md stage table
const workflow = read('WORKFLOW.md');
if (workflow === null) {
  check('WORKFLOW.md: stage table', false, 'file missing');
} else {
  const tableLines = workflow.split('\n').filter((l) => l.trim().startsWith('|'));
  const header = tableLines.find((l) =>
    /stage/i.test(l) && /agent/i.test(l) && /input/i.test(l) && /output/i.test(l) && /gate/i.test(l)
  );
  check('WORKFLOW.md: 5-column header (stage | agent | input | output | gate)', Boolean(header), header ? 'found' : 'not found');

  const dataRows = tableLines.filter((l) => l !== header && !/^\|[\s:-]+\|$/.test(l.replace(/\s/g, '')));
  try {
    const parsed = parseWorkflow(workflow);
    check('WORKFLOW.md: stage table parses', parsed.length > 0, `${parsed.length} stage row(s)`);
  } catch (err) {
    check('WORKFLOW.md: stage table parses', false, err.message);
  }
  check(
    'WORKFLOW.md: data rows present',
    dataRows.length > 0,
    `${dataRows.length} row(s)`,
  );
}

// 4. SYSTEM.md decisions table with evidence pointers
const system = read('SYSTEM.md');
if (system === null) {
  check('SYSTEM.md: decisions table', false, 'file missing');
} else {
  const lines = system.split('\n');
  const evidencePattern = /([\w./-]+\.\w+:L\d+)|(`[^`]+`\s*→)/;
  for (const key of DECISION_KEYS) {
    const line = lines.find((l) => l.toLowerCase().includes(`| ${key}`) || l.toLowerCase().includes(`|${key}`));
    if (!line) {
      check(`SYSTEM.md: decision row "${key}"`, false, 'row not found');
      continue;
    }
    const hasVerdict = /MADE|OPEN/.test(line);
    const hasEvidence = evidencePattern.test(line);
    check(`SYSTEM.md: decision row "${key}"`, hasVerdict && hasEvidence, `verdict=${hasVerdict}, evidence=${hasEvidence}`);
  }
  for (const plane of PLANE_KEYS) {
    const has = lines.some((l) => l.toLowerCase().includes(plane));
    check(`SYSTEM.md: plane "${plane}" mentioned with an owner`, has, has ? 'found' : 'not found');
  }
}

// 5. architecture.json shape
const archRaw = read('architecture.json');
if (archRaw === null) {
  check('architecture.json: parses', false, 'file missing');
} else {
  let arch;
  try {
    arch = JSON.parse(archRaw);
    check('architecture.json: parses', true, 'valid JSON');
  } catch (err) {
    check('architecture.json: parses', false, err.message);
    arch = null;
  }
  if (arch) {
    check('architecture.json: schema id', arch.schema === 'ai-architect.architecture.v1', String(arch.schema));
    check('architecture.json: has generated_at', typeof arch.generated_at === 'string' && arch.generated_at.length > 0);
    check('architecture.json: has goal', typeof arch.goal === 'string' && arch.goal.length > 0);

    const decisions = arch.decisions || {};
    for (const key of DECISION_KEYS) {
      const d = decisions[key];
      const ok = d && ['MADE', 'OPEN'].includes(d.verdict) && typeof d.evidence === 'string' && d.evidence.length > 0 &&
        (d.verdict === 'MADE' || (d.verdict === 'OPEN' && d.deferral_cost));
      check(`architecture.json: decisions.${key}`, Boolean(ok), ok ? 'valid' : 'missing verdict/evidence, or OPEN with no deferral_cost');
    }

    const planes = arch.planes || {};
    for (const key of PLANE_KEYS) {
      const p = planes[key];
      const ok = p && typeof p.owner === 'string' && p.owner.length > 0;
      check(`architecture.json: planes.${key}.owner`, Boolean(ok), ok ? 'valid' : 'missing owner');
    }

    const gates = arch.gates || {};
    for (const id of GATE_IDS) {
      const g = gates[id];
      const ok = g && ['PASS', 'FAIL', 'SKIPPED'].includes(g.status) && Array.isArray(g.evidence);
      check(`architecture.json: gates["${id}"]`, Boolean(ok), ok ? 'valid' : 'missing status/evidence');
    }

    check('architecture.json: artifacts is a non-empty array', Array.isArray(arch.artifacts) && arch.artifacts.length > 0);
  }
}

// 6. prices.json parses and has the right schema (deep economics checks live in check-roi.mjs)
const pricesRaw = read('prices.json');
if (pricesRaw === null) {
  check('prices.json: parses', false, 'file missing');
} else {
  try {
    const prices = JSON.parse(pricesRaw);
    check('prices.json: parses', true, 'valid JSON');
    check('prices.json: schema id', prices.schema === 'ai-architect.prices.v1', String(prices.schema));
    check('prices.json: rows is an array', Array.isArray(prices.rows));
  } catch (err) {
    check('prices.json: parses', false, err.message);
  }
}

// 7. 06-evals/cases.jsonl parses line by line
const cases = read('06-evals/cases.jsonl');
if (cases === null) {
  check('06-evals/cases.jsonl: parses', false, 'file missing');
} else {
  const lines = cases.split('\n').filter((l) => l.trim().length > 0);
  let parseOk = true;
  for (const line of lines) {
    try {
      JSON.parse(line);
    } catch {
      parseOk = false;
      break;
    }
  }
  check('06-evals/cases.jsonl: every line parses as JSON', parseOk, `${lines.length} lines`);
}

// print gate table
const nameWidth = Math.max(...rows.map((r) => r.name.length), 20);
console.log(`check-artifacts: ${path.relative(process.cwd(), targetDir)}`);
console.log(`${'check'.padEnd(nameWidth)}  status    detail`);
console.log('-'.repeat(nameWidth + 60));
for (const r of rows) {
  console.log(`${r.name.padEnd(nameWidth)}  ${r.status.padEnd(8)}  ${r.detail}`);
}
console.log('-'.repeat(nameWidth + 60));
const failCount = rows.filter((r) => r.status === 'FAIL').length;
console.log(`${rows.length} checks, ${rows.length - failCount} pass, ${failCount} fail`);

process.exit(failCount > 0 ? 1 : 0);
