#!/usr/bin/env node
// Installs AI Architect into a harness that does not read .claude-plugin/
// natively (Cursor, or any repo that keeps an AGENTS.md). Run this from
// inside the target repository, or pass --target <dir>.
//
// Usage:
//   node scripts/install-cross-harness.mjs --cursor [--target <dir>]
//   node scripts/install-cross-harness.mjs --agents-md [--target <dir>]
//   node scripts/install-cross-harness.mjs --cursor --agents-md
//
// --cursor     writes one .cursor/rules/ai-architect-<skill>.mdc per skill
//              under skills/, each pointing at that skill's SKILL.md and the
//              /architect lifecycle it serves.
// --agents-md  writes or updates a marked block in <target>/AGENTS.md with
//              the install commands and a pointer to SOP.md.
//
// Idempotent: re-running with the same plugin version reproduces the same
// bytes. The .cursor rule files are fully generated (safe to overwrite). The
// AGENTS.md block is delimited by HTML comment markers and only the content
// between them is replaced — anything else in AGENTS.md is left alone.

import { readFileSync, writeFileSync, existsSync, readdirSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, '..');

const args = process.argv.slice(2);
const doCursor = args.includes('--cursor');
const doAgentsMd = args.includes('--agents-md');
const targetFlagIdx = args.indexOf('--target');
const targetDir = targetFlagIdx >= 0 && args[targetFlagIdx + 1] ? path.resolve(args[targetFlagIdx + 1]) : process.cwd();

if (!doCursor && !doAgentsMd) {
  console.error('install-cross-harness: pass --cursor and/or --agents-md (see file header for usage)');
  process.exit(1);
}

const MARKER_START = '<!-- ai-architect:start -->';
const MARKER_END = '<!-- ai-architect:end -->';

function readFrontmatterField(content, field) {
  const normalized = content.replace(/\r\n/g, '\n');
  const match = normalized.match(/^---\n([\s\S]*?)\n---/);
  if (!match) return null;
  const line = match[1].split('\n').find((l) => l.startsWith(`${field}:`));
  return line ? line.slice(field.length + 1).trim() : null;
}

function cursorRuleFor(skillName, description) {
  return `---
description: "AI Architect skill: ${skillName}"
globs: docs/architecture/**
alwaysApply: false
---

This repo has the AI Architect plugin installed. The \`${skillName}\` skill covers:

${description}

Read \`skills/${skillName}/SKILL.md\` in the AI Architect plugin for the full instructions before
doing this work by hand. If \`docs/architecture/SOP.md\` exists, read it first — every AI Architect
command loads it before acting.

This file is generated by \`scripts/install-cross-harness.mjs --cursor\`. Do not hand-edit it —
edit the skill's SKILL.md instead and re-run the installer.
`;
}

let wrote = [];
let skipped = [];

if (doCursor) {
  const skillsRoot = path.join(repoRoot, 'skills');
  const skillDirs = existsSync(skillsRoot)
    ? readdirSync(skillsRoot, { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => e.name)
    : [];

  const rulesDir = path.join(targetDir, '.cursor', 'rules');
  mkdirSync(rulesDir, { recursive: true });

  for (const skillName of skillDirs) {
    const skillMdPath = path.join(skillsRoot, skillName, 'SKILL.md');
    if (!existsSync(skillMdPath)) continue;
    const content = readFileSync(skillMdPath, 'utf8');
    const description = readFrontmatterField(content, 'description') || '(no description found in SKILL.md)';
    const outPath = path.join(rulesDir, `ai-architect-${skillName}.mdc`);
    const newContent = cursorRuleFor(skillName, description);
    if (existsSync(outPath) && readFileSync(outPath, 'utf8') === newContent) {
      skipped.push(path.relative(targetDir, outPath));
      continue;
    }
    writeFileSync(outPath, newContent, 'utf8');
    wrote.push(path.relative(targetDir, outPath));
  }
}

if (doAgentsMd) {
  const agentsPath = path.join(targetDir, 'AGENTS.md');
  const blockBody = `${MARKER_START}
## AI Architect

This repo has the AI Architect plugin available. Run \`/architect "<goal>"\` to start the gated
architecture lifecycle (frame, discover, flow, decide, cost, secure, prove, operate, verify); it
writes an evidence-backed artifact set into \`docs/architecture/\`.

If \`docs/architecture/SOP.md\` exists, read it before running any AI Architect command or doing
this work by hand — it governs model routing, write scopes, stop conditions, and human gates.

Install: \`/plugin marketplace add frankxai/ai-architect\` then \`/plugin install ai-architect@frankx\`,
or \`npx skills add frankxai/ai-architect\` for a harness without a plugin system.
${MARKER_END}`;

  if (!existsSync(agentsPath)) {
    writeFileSync(agentsPath, `# Agents\n\n${blockBody}\n`, 'utf8');
    wrote.push(path.relative(targetDir, agentsPath));
  } else {
    const existing = readFileSync(agentsPath, 'utf8');
    const startIdx = existing.indexOf(MARKER_START);
    const endIdx = existing.indexOf(MARKER_END);
    let next;
    if (startIdx >= 0 && endIdx >= 0) {
      next = existing.slice(0, startIdx) + blockBody + existing.slice(endIdx + MARKER_END.length);
    } else {
      const sep = existing.endsWith('\n') ? '\n' : '\n\n';
      next = existing + sep + blockBody + '\n';
    }
    if (next === existing) {
      skipped.push(path.relative(targetDir, agentsPath));
    } else {
      writeFileSync(agentsPath, next, 'utf8');
      wrote.push(path.relative(targetDir, agentsPath));
    }
  }
}

console.log(`install-cross-harness: target ${targetDir}`);
for (const f of wrote) console.log(`  wrote   ${f}`);
for (const f of skipped) console.log(`  unchanged ${f}`);
if (wrote.length === 0 && skipped.length === 0) console.log('  nothing to do');
